"""Turn the daily market weather table into leakage-safe model features.

Run from backend/ after fetch_price_weather:  python -m scripts.build_weather_features

Output: dataset/weather/weather_features_daily.parquet (market, date, WEATHER_FEATURES) and
dataset/reports/weather_data_quality.md. See app/ml/price_prediction/weather_features.py for
the feature definitions and the availability rules.
"""
from __future__ import annotations

import pandas as pd

from app.ml.common import paths
from app.ml.price_prediction.weather_features import (CLIMATOLOGY_END_YEAR, WEATHER_FEATURES,
                                                      add_state_series, build_weather_features)

WEATHER_DIR = paths.DATASET_DIR / "weather"


def md_table(df: pd.DataFrame) -> str:
    rows = ["| feature | " + " | ".join(df.columns) + " |", "|---" * (len(df.columns) + 1) + "|"]
    rows += [f"| {i} | " + " | ".join(str(v) for v in r) + " |" for i, r in zip(df.index, df.values)]
    return "\n".join(rows)


def main() -> None:
    w = pd.read_parquet(WEATHER_DIR / "market_weather_daily.parquet")
    daily = add_state_series(w)
    feats = build_weather_features(daily)
    feats.to_parquet(WEATHER_DIR / "weather_features_daily.parquet", index=False)

    price = pd.read_parquet(paths.PRICE_CLEAN_PATH, columns=["Market", "Date"])
    m = price.merge(feats.rename(columns={"market": "Market", "date": "Date"}),
                    on=["Market", "Date"], how="left")
    covered = m[WEATHER_FEATURES].notna().all(axis=1)
    loc = pd.read_csv(paths.CROP_PRICE_DIR / "market_locations.csv")
    L = ["# Weather Data — Quality Report", "",
         "Generated by `scripts/build_weather_features.py`.", "",
         "## Source", "",
         "- Open-Meteo Archive API, ERA5-family reanalysis (`best_match`), daily values, timezone "
         "Asia/Kolkata. Units: temperature °C, precipitation mm/day, relative humidity %.",
         "- This is *observed/reanalysed* weather, not an archived forecast. It is used only as "
         "trailing information up to the forecast origin, plus normals from years "
         f"<= {CLIMATOLOGY_END_YEAR}.", "",
         "## Coverage", "",
         f"- Markets in price data: {loc['market'].nunique()}; mapped to a location: "
         f"{int((loc['status'] == 'mapped').sum())}; ambiguous: {int((loc['status'] == 'ambiguous').sum())}; "
         f"not found: {int((loc['status'] == 'not_found').sum())}.",
         f"- Share of cleaned price rows with a complete weather feature set: **{covered.mean():.1%}** "
         f"({int(covered.sum()):,} of {len(m):,}). The rest have no mapped market and keep NaN.",
         f"- Weather days per market: {w.groupby('market').size().min()}–{w.groupby('market').size().max()}.",
         f"- Days with any missing weather value: {int(w[['temperature_mean','precipitation','relative_humidity']].isna().any(axis=1).sum())}.",
         "", "## Feature summary (price-row weighted)", "",
         md_table(m[WEATHER_FEATURES].describe().round(2).T), "",
         "## Limitations", "",
         "- Market coordinates are town centroids from GeoNames, matched by name (see "
         "`dataset/crop_price/market_locations.csv`); they are not surveyed yard positions.",
         "- Reanalysis grid cells are ~25 km; neighbouring markets can share a cell.",
         "- The state-level series uses the plain mean of all mapped markets' weather.",
         "- No archived day-ahead weather forecasts are used, so no weather *forecast* feature "
         "exists in the model."]
    (paths.REPORTS_DIR / "weather_data_quality.md").write_text("\n".join(L), encoding="utf-8")
    print(f"features rows={len(feats):,}; price rows with weather={covered.mean():.1%}")


if __name__ == "__main__":
    main()
